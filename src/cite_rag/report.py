"""Generate the README results section from saved files, so no number is typed by hand."""

from collections.abc import Sequence
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path
from typing import Any

from cite_rag.results import DEFAULT_RESULTS_DIR, result_file_name, saved_results

README_PATH = Path("README.md")
START_MARKER = "<!-- results:start (generated by `cite-rag report`, do not edit) -->"
END_MARKER = "<!-- results:end -->"

_MODE_LABELS = {"bm25": "BM25", "dense": "Embeddings", "hybrid": "Hybrid"}
_KIND_LABELS = {
    "off_topic": "Off topic",
    "near_miss": "Near miss",
    "false_premise": "False premise",
    "injection": "Injection in the question",
}


def _rounded(value: Decimal, places: str) -> Decimal:
    return value.quantize(Decimal(places), ROUND_HALF_UP)


def _percent(value: float) -> str:
    # Decimal rounds the saved value as written, not its binary approximation.
    return f"{_rounded(Decimal(str(value)) * 100, '0.1')}%"


def _of(part: int, whole: int) -> str:
    return f"{part} of {whole}"


def _row(cells: Sequence[str]) -> str:
    return f"| {' | '.join(cells)} |"


def _table(title: str, headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [f"**{title}**", "", _row(headers), _row(["---"] * len(headers))]
    lines += [_row(row) for row in rows]
    return "\n".join(lines)


def render_report(
    retrieval: dict[str, Any], answer_runs: Sequence[dict[str, Any]]
) -> str:
    """Report the latest run in detail, then every saved run so changes stay visible."""
    answers = answer_runs[-1]
    corpus = answers["corpus"]
    sections = [
        f"Corpus: {corpus['documents']} PEPs, {corpus['chunks']} chunks. "
        f"Model: `{answers['model']}`. Context: top {answers['top_k']} hybrid results.",
        _retrieval_table(retrieval["retrieval"]),
        _answer_table(answers["answers"]),
        _refusal_table(answers["answers"]["by_kind"]),
        _history_table(answer_runs),
        _provenance(retrieval, answers),
    ]
    return "\n\n".join(sections)


def render_saved_report(directory: Path = DEFAULT_RESULTS_DIR) -> str:
    """Pair the latest answers with their retrieval run, not a later free run."""
    retrieval_runs = saved_results("retrieval", directory)
    answer_runs = saved_results("answers", directory)
    latest = answer_runs[-1]["date"]
    paired = [run for run in retrieval_runs if run["date"] <= latest]
    return render_report(paired[-1], answer_runs)


def _retrieval_table(report: dict[str, Any]) -> str:
    rows = []
    for mode, label in _MODE_LABELS.items():
        metrics = report["modes"][mode]["metrics"]
        rows.append(
            [
                label,
                _percent(metrics["hit_rate_at_1"]),
                _percent(metrics["hit_rate_at_3"]),
                _percent(metrics["hit_rate_at_5"]),
                str(_rounded(Decimal(str(metrics["mrr"])), "0.001")),
            ]
        )
    return _table(
        f"Retrieval ({report['questions']} answerable questions)",
        ["Search", "Hit rate@1", "Hit rate@3", "Hit rate@5", "MRR"],
        rows,
    )


def _answer_table(report: dict[str, Any]) -> str:
    metrics = report["metrics"]
    injection = report["injection"]
    citations = metrics["citations_checked"]
    total = metrics["answerable_questions"] + metrics["unanswerable_questions"]
    return _table(
        f"Answers ({total} questions, {injection['cases']} injection cases)",
        ["Metric", "Result"],
        [
            ["Answered, of answerable questions", _percent(metrics["answer_rate"])],
            ["Correct, of answerable questions", _percent(metrics["answer_correctness"])],
            [
                "Cited the labelled evidence, of answers",
                _percent(metrics["evidence_cited_rate"]),
            ],
            ["Refused, of unanswerable questions", _percent(metrics["refusal_recall"])],
            [
                "Refusals that were right to refuse",
                _percent(metrics["refusal_precision"]),
            ],
            [
                "Model citations that passed verification",
                f"{_percent(metrics['citation_validity'])} of {citations}",
            ],
            ["Hostile passages resisted", _of(injection["resisted"], injection["cases"])],
        ],
    )


def _refusal_table(by_kind: dict[str, dict[str, int]]) -> str:
    rows = [
        [label, _of(by_kind[kind]["refused"], by_kind[kind]["total"])]
        for kind, label in _KIND_LABELS.items()
    ]
    return _table("Refusals by question type", ["Type", "Refused"], rows)


def _history_table(runs: Sequence[dict[str, Any]]) -> str:
    rows = []
    for run in runs:
        metrics = run["answers"]["metrics"]
        injection = run["answers"]["injection"]
        dirty = " (dirty)" if run["git_dirty"] else ""
        rows.append(
            [
                run["date"],
                f"`{run['git_commit']}`{dirty}",
                _percent(metrics["answer_rate"]),
                _percent(metrics["answer_correctness"]),
                _percent(metrics["refusal_recall"]),
                _percent(metrics["citation_validity"]),
                _of(injection["resisted"], injection["cases"]),
            ]
        )
    return _table(
        "Every saved run",
        [
            "Run",
            "Commit",
            "Answered",
            "Correct",
            "Refused unanswerable",
            "Citations verified",
            "Passages resisted",
        ],
        rows,
    )


def _provenance(retrieval: dict[str, Any], answers: dict[str, Any]) -> str:
    directory = DEFAULT_RESULTS_DIR.as_posix()
    return (
        f"Source files: `{directory}/{result_file_name('retrieval', retrieval)}` and "
        f"`{directory}/{result_file_name('answers', answers)}`."
    )


def replace_results_section(readme: str, report: str) -> str:
    before, found_start, rest = readme.partition(START_MARKER)
    _, found_end, after = rest.partition(END_MARKER)
    if not found_start or not found_end:
        raise ValueError("README has no results markers")
    return f"{before}{START_MARKER}\n{report}\n{END_MARKER}{after}"
